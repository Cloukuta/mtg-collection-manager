function corsHeaders(
  origin
) {

  return {

    "Access-Control-Allow-Origin":
      origin ||
      "*",

    "Access-Control-Allow-Methods":
      "POST, GET, OPTIONS",

    "Access-Control-Allow-Headers":
      "content-type, x-app-token",

    "Access-Control-Max-Age":
      "86400",

    "Vary":
      "Origin"
  };
}


/* ============================================================
   JSON RESPONSE
============================================================ */

function json(
  body,
  status,
  origin
) {

  return new Response(
    JSON.stringify(
      body
    ),
    {
      status,

      headers: {

        "Content-Type":
          "application/json",

        ...corsHeaders(
          origin
        )
      }
    }
  );
}


/* ============================================================
   WAIT
============================================================ */

function sleep(
  milliseconds
) {

  return new Promise(
    (resolve) =>
      setTimeout(
        resolve,
        milliseconds
      )
  );
}


/* ============================================================
   ARRAYBUFFER → BASE64
============================================================ */

function arrayBufferToBase64(
  buffer
) {

  const bytes =
    new Uint8Array(
      buffer
    );


  let binary =
    "";


  const chunkSize =
    0x8000;


  for (
    let i = 0;
    i < bytes.length;
    i += chunkSize
  ) {

    binary +=
      String.fromCharCode.apply(
        null,
        bytes.subarray(
          i,
          i + chunkSize
        )
      );
  }


  return btoa(
    binary
  );
}


/* ============================================================
   MODEL CHAIN
============================================================ */

function getModelChain(
  env
) {

  const models = [

    env.GEMINI_MODEL ||
      DEFAULT_PRIMARY_MODEL,

    env.GEMINI_FALLBACK_MODEL ||
      DEFAULT_FALLBACK_MODEL,

    env.GEMINI_FALLBACK_MODEL_2 ||
      DEFAULT_FALLBACK_MODEL_2
  ];


  /*
    Remove empty values and duplicates.

    This allows us to temporarily configure:

      primary = model A
      fallback = model A

    without actually calling the same fallback twice.
  */

  return [
    ...new Set(
      models
        .map(
          (model) =>
            String(
              model ||
              ""
            ).trim()
        )
        .filter(
          Boolean
        )
    )
  ];
}


/* ============================================================
   TEMPORARY / FALLBACK ELIGIBLE ERRORS
============================================================ */

function isTransientStatus(
  status
) {

  return (
    status === 429 ||
    status === 500 ||
    status === 502 ||
    status === 503 ||
    status === 504
  );
}


/*
  404 is treated differently.

  We do NOT retry the same model because it usually means
  the model ID is unavailable.

  We DO allow moving to the next model.
*/

function canFallbackFromStatus(
  status
) {

  return (
    status === 404 ||
    isTransientStatus(
      status
    )
  );
}


/* ============================================================
   SAFE JSON TEXT PARSER
============================================================ */

function parseGeminiJson(
  text
) {

  if (
    !text
  ) {

    throw new Error(
      "Gemini returned empty output."
    );
  }


  let cleaned =
    String(
      text
    ).trim();


  /*
    Structured output normally returns raw JSON,
    but this protects us if a model unexpectedly
    wraps it in a markdown code block.
  */

  if (
    cleaned.startsWith(
      "```"
    )
  ) {

    cleaned =
      cleaned
        .replace(
          /^```(?:json)?\s*/i,
          ""
        )
        .replace(
          /\s*```$/,
          ""
        )
        .trim();
  }


  return JSON.parse(
    cleaned
  );
}


/* ============================================================
   NORMALIZATION
============================================================ */

function cleanNullableString(
  value
) {

  if (
    value == null
  ) {

    return null;
  }


  const text =
    String(
      value
    ).trim();


  if (
    !text
  ) {

    return null;
  }


  return text;
}


function normalizeCollectorNumber(
  value
) {

  const text =
    cleanNullableString(
      value
    );


  if (
    !text
  ) {

    return null;
  }


  /*
    Remove leading zeroes only when followed by a digit.

    Examples:

      0095  -> 95
      0410  -> 410
      001a  -> 1a

    Does not destroy prefixes/suffixes.
  */

  return text.replace(
    /^0+(?=\d)/,
    ""
  );
}


function normalizeConfidence(
  value
) {

  const number =
    Number(
      value
    );


  if (
    !Number.isFinite(
      number
    )
  ) {

    return 0;
  }


  return Math.max(
    0,
    Math.min(
      1,
      number
    )
  );
}


function normalizeSingleResult(
  result
) {

  return {

    name:
      cleanNullableString(
        result?.name
      ),

    set_code:
      cleanNullableString(
        result?.set_code
      )
        ?.toLowerCase() ||
      null,

    collector_number:
      normalizeCollectorNumber(
        result?.collector_number
      ),

    language:
      cleanNullableString(
        result?.language
      )
        ?.toLowerCase() ||
      "en",

    /*
      Finish is controlled by the app.
      Gemini is intentionally not authoritative here.
    */
    foil:
      false,

    confidence:
      normalizeConfidence(
        result?.confidence
      )
  };
}


function normalizeBatchResult(
  result
) {

  const cards =
    Array.isArray(
      result?.cards
    )
      ? result.cards
      : [];


  const normalized =
    cards
      .map(
        (
          card,
          index
        ) => {

          const slot =
            Math.max(
              1,
              Math.round(
                Number(
                  card?.slot
                ) ||
                index + 1
              )
            );


          return {

            slot,

            name:
              cleanNullableString(
                card?.name
              ),

            set_code:
              cleanNullableString(
                card?.set_code
              )
                ?.toLowerCase() ||
              null,

            collector_number:
              normalizeCollectorNumber(
                card?.collector_number
              ),

            language:
              cleanNullableString(
                card?.language
              )
                ?.toLowerCase() ||
              "en",

            /*
              Finish is selected manually in Rapid Batch.
            */
            foil:
              false,

            confidence:
              normalizeConfidence(
                card?.confidence
              )
          };
        }
      );


  normalized.sort(
    (
      a,
      b
    ) =>
      a.slot -
      b.slot
  );


  return {
    cards:
      normalized
  };
}


/* ============================================================
   BUILD GEMINI PAYLOAD
============================================================ */

function buildGeminiPayload({
  prompt,
  schema,
  mime,
  base64
}) {

  return {

    contents: [
      {
        parts: [

          {
            text:
              prompt
          },

          {
            inline_data: {

              mime_type:
                mime,

              data:
                base64
            }
          }
        ]
      }
    ],

    generationConfig: {

      responseMimeType:
        "application/json",

      responseSchema:
        schema,

      /*
        We do not need deep reasoning for OCR-like
        identification of set code + collector number.
      */
      thinkingConfig: {
        thinkingLevel:
          "minimal"
      }
    }
  };
}


/* ============================================================
   ONE GEMINI REQUEST
============================================================ */

async function callGeminiModel({
  model,
  apiKey,
  payload,
  timeoutMs
}) {

  const controller =
    new AbortController();


  const timeout =
    setTimeout(
      () =>
        controller.abort(),
      timeoutMs
    );


  const endpoint =
    `https://generativelanguage.googleapis.com/v1beta/models/` +
    `${encodeURIComponent(model)}:generateContent?key=` +
    `${encodeURIComponent(apiKey)}`;


  try {

    let response;


    try {

      response =
        await fetch(
          endpoint,
          {
            method:
              "POST",

            headers: {
              "Content-Type":
                "application/json"
            },

            body:
              JSON.stringify(
                payload
              ),

            signal:
              controller.signal
          }
        );

    } catch (
      error
    ) {

      if (
        error?.name ===
        "AbortError"
      ) {

        return {
          ok:
            false,

          model,

          kind:
            "timeout",

          transient:
            true,

          canFallback:
            true,

          error:
            "Gemini timeout"
        };
      }


      return {
        ok:
          false,

        model,

        kind:
          "network",

        transient:
          true,

        canFallback:
          true,

        error:
          "Gemini fetch failed: " +
          (
            error?.message ||
            "network error"
          )
      };
    }


    if (
      !response.ok
    ) {

      const detail =
        await response.text();


      return {

        ok:
          false,

        model,

        kind:
          "http",

        status:
          response.status,

        transient:
          isTransientStatus(
            response.status
          ),

        canFallback:
          canFallbackFromStatus(
            response.status
          ),

        error:
          `Gemini error ${response.status}`,

        detail:
          detail.slice(
            0,
            800
          )
      };
    }


    let data;


    try {

      data =
        await response.json();

    } catch (
      error
    ) {

      return {

        ok:
          false,

        model,

        kind:
          "response",

        transient:
          true,

        canFallback:
          true,

        error:
          "Gemini returned invalid response JSON."
      };
    }


    const text =
      data
        ?.candidates
        ?.[0]
        ?.content
        ?.parts
        ?.[0]
        ?.text;


    if (
      !text
    ) {

      return {

        ok:
          false,

        model,

        kind:
          "empty",

        transient:
          true,

        canFallback:
          true,

        error:
          "No result from Gemini."
      };
    }


    let parsed;


    try {

      parsed =
        parseGeminiJson(
          text
        );

    } catch (
      error
    ) {

      return {

        ok:
          false,

        model,

        kind:
          "parse",

        transient:
          true,

        canFallback:
          true,

        error:
          "Unparseable Gemini output.",

        detail:
          String(
            text
          ).slice(
            0,
            500
          )
      };
    }


    return {

      ok:
        true,

      model,

      result:
        parsed
    };

  } finally {

    clearTimeout(
      timeout
    );
  }
}


/* ============================================================
   GEMINI FALLBACK ENGINE
============================================================ */

async function callGeminiWithFallback({
  env,
  payload,
  timeoutMs
}) {

  const models =
    getModelChain(
      env
    );


  const attempts =
    [];


  for (
    let modelIndex = 0;
    modelIndex < models.length;
    modelIndex++
  ) {

    const model =
      models[
        modelIndex
      ];


    /*
      The PRIMARY model receives one automatic retry.

      Fallback models receive one attempt each.

      This gives us:

        primary attempt
        primary retry
        fallback 1
        fallback 2

      without creating a large retry storm.
    */

    const maxAttempts =
      modelIndex === 0
        ? 2
        : 1;


    for (
      let attempt = 1;
      attempt <= maxAttempts;
      attempt++
    ) {

      const response =
        await callGeminiModel({
          model,

          apiKey:
            env.GEMINI_API_KEY,

          payload,

          timeoutMs
        });


      attempts.push({

        model,

        attempt,

        ok:
          response.ok,

        status:
          response.status ||
          null,

        kind:
          response.kind ||
          null
      });


      if (
        response.ok
      ) {

        return {

          ok:
            true,

          result:
            response.result,

          model:
            response.model,

          fallbackUsed:
            modelIndex > 0,

          attempts
        };
      }


      /*
        Do NOT blindly retry permanent errors.

        Example:

          400 bad request
          401 bad key
          403 permission problem

        A different model is unlikely to solve those.
      */

      if (
        !response.canFallback
      ) {

        return {

          ok:
            false,

          error:
            response.error,

          detail:
            response.detail ||
            null,

          status:
            response.status ||
            null,

          model:
            response.model,

          attempts
        };
      }


      /*
        Retry PRIMARY only for transient failures.

        A 404 should skip immediately to the fallback because
        retrying an unavailable model ID is pointless.
      */

      const shouldRetryPrimary =
        modelIndex === 0 &&
        attempt < maxAttempts &&
        response.transient;


      if (
        shouldRetryPrimary
      ) {

        await sleep(
          PRIMARY_RETRY_DELAY_MS
        );


        continue;
      }


      /*
        Move to the next model.
      */

      break;
    }
  }


  return {

    ok:
      false,

    error:
      "AI service is temporarily unavailable.",

    detail:
      "All configured Gemini models failed.",

    attempts
  };
}


/* ============================================================
   AUTHORIZATION
============================================================ */

function checkOrigin(
  origin,
  allowed
) {

  if (
    allowed &&
    origin &&
    origin !== allowed
  ) {

    return false;
  }


  return true;
}


/* ============================================================
   RATE LIMIT
============================================================ */

async function checkRateLimit(
  request,
  env
) {

  if (
    !env.RATE_LIMITER
  ) {

    return true;
  }


  const ip =
    request.headers.get(
      "CF-Connecting-IP"
    ) ||
    "anon";


  const result =
    await env.RATE_LIMITER.limit({
      key:
        ip
    });


  return !!result.success;
}


/* ============================================================
   READ IMAGE
============================================================ */

async function readImage(
  request
) {

  const buffer =
    await request.arrayBuffer();


  if (
    !buffer.byteLength ||
    buffer.byteLength >
      MAX_IMAGE_BYTES
  ) {

    throw new Error(
      "bad image size"
    );
  }


  return {

    buffer,

    base64:
      arrayBufferToBase64(
        buffer
      ),

    mime:
      request.headers.get(
        "Content-Type"
      ) ||
      "image/jpeg"
  };
}


/* ============================================================
   SINGLE IDENTIFICATION
============================================================ */

async function identifySingle({
  env,
  image
}) {

  const payload =
    buildGeminiPayload({

      prompt:
        SINGLE_PROMPT,

      schema:
        SINGLE_SCHEMA,

      mime:
        image.mime,

      base64:
        image.base64
    });


  const response =
    await callGeminiWithFallback({

      env,

      payload,

      timeoutMs:
        SINGLE_TIMEOUT_MS
    });


  if (
    !response.ok
  ) {

    return response;
  }


  return {

    ...response,

    result:
      normalizeSingleResult(
        response.result
      )
  };
}


