/* ============================================================
   WORKER
============================================================ */

export default {

  async fetch(
    request,
    env
  ) {

    const url =
      new URL(
        request.url
      );


    const origin =
      request.headers.get(
        "Origin"
      );


    const allowed =
      env.ALLOWED_ORIGIN ||
      "";


    const responseOrigin =
      allowed ||
      origin;


    /* ========================================================
       CORS PREFLIGHT
    ======================================================== */

    if (
      request.method ===
      "OPTIONS"
    ) {

      return new Response(
        null,
        {
          status:
            204,

          headers:
            corsHeaders(
              responseOrigin
            )
        }
      );
    }


    /* ========================================================
       HEALTH
    ======================================================== */

    if (
      url.pathname ===
        "/health" &&
      request.method ===
        "GET"
    ) {

      const models =
        getModelChain(
          env
        );


      return json(
        {

          ok:
            true,

          endpoints: [
            "/identify",
            "/identify-batch"
          ],

          model:
            models[0] ||
            null,

          models: {

            primary:
              models[0] ||
              null,

            fallbacks:
              models.slice(
                1
              )
          },

          ratelimit:
            !!env.RATE_LIMITER
        },

        200,

        responseOrigin
      );
    }


    /* ========================================================
       VALID ROUTES
    ======================================================== */

    const isSingle =
      url.pathname ===
        "/identify";


    const isBatch =
      url.pathname ===
        "/identify-batch";


    if (
      request.method !==
        "POST" ||
      (
        !isSingle &&
        !isBatch
      )
    ) {

      return json(
        {
          error:
            "not found"
        },

        404,

        responseOrigin
      );
    }


    /* ========================================================
       ORIGIN CHECK
    ======================================================== */

    if (
      !checkOrigin(
        origin,
        allowed
      )
    ) {

      return json(
        {
          error:
            "forbidden origin"
        },

        403,

        allowed
      );
    }


    /* ========================================================
       APP TOKEN
    ======================================================== */

    if (
      !env.APP_TOKEN ||
      request.headers.get(
        "x-app-token"
      ) !== env.APP_TOKEN
    ) {

      return json(
        {
          error:
            "unauthorized"
        },

        401,

        responseOrigin
      );
    }


    /* ========================================================
       RATE LIMIT
    ======================================================== */

    try {

      const allowedByRateLimit =
        await checkRateLimit(
          request,
          env
        );


      if (
        !allowedByRateLimit
      ) {

        return json(
          {
            error:
              "rate limited — too many scans, wait a moment and retry"
          },

          429,

          responseOrigin
        );
      }

    } catch (
      error
    ) {

      /*
        Rate limiter failure should not make the entire app
        unusable. Gemini quota still acts as a backstop.
      */

      console.error(
        "Rate limiter error:",
        error
      );
    }


    /* ========================================================
       GEMINI CONFIG
    ======================================================== */

    if (
      !env.GEMINI_API_KEY
    ) {

      return json(
        {
          error:
            "server not configured (no GEMINI_API_KEY)"
        },

        500,

        responseOrigin
      );
    }


    /* ========================================================
       IMAGE
    ======================================================== */

    let image;


    try {

      image =
        await readImage(
          request
        );

    } catch (
      error
    ) {

      return json(
        {
          error:
            "bad image size"
        },

        400,

        responseOrigin
      );
    }


    /* ========================================================
       IDENTIFY
    ======================================================== */

    let result;


    try {

      result =
        isBatch
          ? await identifyBatch({
              env,
              image
            })
          : await identifySingle({
              env,
              image
            });

    } catch (
      error
    ) {

      console.error(
        "Identification error:",
        error
      );


      return json(
        {
          error:
            "AI identification failed",

          detail:
            error?.message ||
            "unknown error"
        },

        502,

        responseOrigin
      );
    }


    /* ========================================================
       ALL MODELS FAILED
    ======================================================== */

    if (
      !result.ok
    ) {

      /*
        Permanent configuration/API errors retain 502.

        Temporary availability failures return 503 so we can
        distinguish them later in the frontend if desired.
      */

      const hasTemporaryFailure =
        result.attempts
          ?.some(
            (attempt) =>
              attempt.kind ===
                "timeout" ||
              attempt.kind ===
                "network" ||
              isTransientStatus(
                attempt.status
              )
          );


      const status =
        hasTemporaryFailure
          ? 503
          : 502;


      return json(
        {

          error:
            result.error ||
            "AI identification failed",

          detail:
            result.detail ||
            null,

          attempts:
            result.attempts ||
            []
        },

        status,

        responseOrigin
      );
    }


    /* ========================================================
       SUCCESS
    ======================================================== */

    return json(
      {

        ok:
          true,

        result:
          result.result,

        /*
          Debugging information.

          Existing frontend ignores these fields,
          so this does not break Single Scan or Rapid Batch.
        */

        model:
          result.model,

        fallback_used:
          !!result.fallbackUsed,

        attempts:
          result.attempts
      },

      200,

      responseOrigin
    );
  }
};