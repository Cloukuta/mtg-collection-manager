function createPriceCell(
  entry,
  provider
) {

  const td =
    document.createElement(
      "td"
    );


  td.className =
    "price-cell";


  if (
    !priceDatabase
  ) {

    td.textContent =
      "—";


    td.classList.add(
      "price-na"
    );


    return td;
  }


  const point =
    getEntryPrice(
      entry,
      provider
    );


  if (
    !point
  ) {

    td.textContent =
      "N/D";


    td.classList.add(
      "price-na"
    );


    const finish =
      getEntryFinish(
        entry
      );


    if (
      !PRICE_FINISH_MAP[
        finish
      ]
    ) {

      td.title =
        "No safe price mapping for this finish.";
    }


    return td;
  }


  td.textContent =
    priceMoney(
      point.price
    );


  if (
    point.date
  ) {

    td.title =
      `Price date: ${point.date}`;
  }


  return td;
}


function renderPriceColumns() {

  ensurePriceHeaders();


  const rows =
    Array.from(
      document.querySelectorAll(
        "#tbody tr"
      )
    );


  rows.forEach(
    (row, index) => {

      row
        .querySelectorAll(
          ".price-cell"
        )
        .forEach(
          (cell) =>
            cell.remove()
        );


      const entry =
        collected[
          index
        ];


      if (
        !entry
      ) {

        return;
      }


      const removeCell =
        row.lastElementChild;


      row.insertBefore(
        createPriceCell(
          entry,
          "cardkingdom"
        ),
        removeCell
      );


      row.insertBefore(
        createPriceCell(
          entry,
          "starcitygames"
        ),
        removeCell
      );
    }
  );
}


function renderPriceSummary() {

  ensurePriceSummary();


  const ckTotal =
    document.getElementById(
      "cardKingdomTotal"
    );


  const scgTotal =
    document.getElementById(
      "starCityGamesTotal"
    );


  const meta =
    document.getElementById(
      "priceMeta"
    );


  if (
    ckTotal
  ) {

    ckTotal.textContent =
      priceDatabase
        ? formatProviderTotal(
            "cardkingdom"
          )
        : "—";
  }


  if (
    scgTotal
  ) {

    scgTotal.textContent =
      priceDatabase
        ? formatProviderTotal(
            "starcitygames"
          )
        : "—";
  }


  if (
    !meta
  ) {

    return;
  }


  if (
    priceLoading
  ) {

    meta.textContent =
      "Loading price database…";


    return;
  }


  if (
    priceLoadError
  ) {

    meta.textContent =
      "Prices unavailable. Use Refresh prices to try again.";


    return;
  }


  if (
    !priceDatabase
  ) {

    meta.textContent =
      "Prices load when Scan List is opened.";


    return;
  }


  const generated =
    priceDatabase.meta?.generated_at;


  const source =
    priceDatabase.meta?.cardkingdom_source ||
    "MTGJSON";


  const dateText =
    generated
      ? new Date(
          generated
        ).toLocaleString()
      : "Unknown date";


  meta.textContent =
    `Card Kingdom source: ${source} · Updated: ${dateText} · ` +
    "SCG remains N/D until an authorized source is connected.";
}


