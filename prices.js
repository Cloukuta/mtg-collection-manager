/* ============================================================
   PRICE CSV EXPORT
============================================================ */

async function exportPriceListCsv() {

  if (
    collected.length === 0
  ) {

    setStatus(
      "Nothing to export yet."
    );


    return;
  }


  if (
    !priceDatabase
  ) {

    setStatus(
      "Loading prices before export…"
    );


    const ok =
      await loadPriceDatabase();


    if (
      !ok
    ) {

      setStatus(
        "Price List CSV could not be created because prices are unavailable."
      );


      return;
    }
  }


  const header = [
    "Name",
    "Set",
    "Collector Number",
    "Quantity",
    "Finish",
    "Card Kingdom Price",
    "Card Kingdom Total",
    "Star City Games Price",
    "Star City Games Total"
  ];


  let ckGrandTotal = 0;
  let scgGrandTotal = 0;


  const rows =
    collected.map(
      (entry) => {

        const qty =
          Math.max(
            1,
            Number(
              entry.qty
            ) ||
            1
          );


        const ck =
          getEntryPrice(
            entry,
            "cardkingdom"
          );


        const scg =
          getEntryPrice(
            entry,
            "starcitygames"
          );


        const ckTotal =
          ck
            ? ck.price *
              qty
            : null;


        const scgTotal =
          scg
            ? scg.price *
              qty
            : null;


        if (
          ckTotal != null
        ) {

          ckGrandTotal +=
            ckTotal;
        }


        if (
          scgTotal != null
        ) {

          scgGrandTotal +=
            scgTotal;
        }


        return [
          entry.card?.name ||
            "Unknown Card",

          (
            entry.card?.set ||
            ""
          ).toUpperCase(),

          entry.card?.collector_number ||
            "",

          qty,

          getEntryFinishLabel(
            entry
          ),

          ck
            ? priceNumberForCsv(
                ck.price
              )
            : "",

          ckTotal != null
            ? priceNumberForCsv(
                ckTotal
              )
            : "",

          scg
            ? priceNumberForCsv(
                scg.price
              )
            : "",

          scgTotal != null
            ? priceNumberForCsv(
                scgTotal
              )
            : ""
        ];
      }
    );


  const ckCoverage =
    getProviderTotal(
      "cardkingdom"
    );


  const scgCoverage =
    getProviderTotal(
      "starcitygames"
    );


  const totalQty =
    collected.reduce(
      (
        total,
        entry
      ) =>
        total +
        Math.max(
          1,
          Number(
            entry.qty
          ) ||
          1
        ),
      0
    );


  rows.push([
    "TOTAL",
    "",
    "",
    totalQty,
    "",
    "",
    ckCoverage.pricedLines
      ? priceNumberForCsv(
          ckGrandTotal
        )
      : "",
    "",
    scgCoverage.pricedLines
      ? priceNumberForCsv(
          scgGrandTotal
        )
      : ""
  ]);


  const csv =
    priceToCsv([
      header,
      ...rows
    ]);


  const blob =
    new Blob(
      [
        "\uFEFF",
        csv
      ],
      {
        type:
          "text/csv;charset=utf-8"
      }
    );


  const anchor =
    document.getElementById(
      "dl"
    ) ||
    document.createElement(
      "a"
    );


  const url =
    URL.createObjectURL(
      blob
    );


  anchor.href =
    url;


  anchor.download =
    "scan_list_prices.csv";


  anchor.click();


  setTimeout(
    () =>
      URL.revokeObjectURL(
        url
      ),
    2000
  );


  setStatus(
    `Exported ${collected.length} line(s) → scan_list_prices.csv`
  );
}


