/* ============================================================
   MTG Card Scanner — Scan List prices

   Adds Card Kingdom / Star City Games pricing to the existing
   Scan List without changing the internal collection logic.

   Requirements:
   - app.js must load before this file.
   - batch-identify.js may load before this file.
   - data/prices.json is generated by scripts/build_prices.py.
============================================================ */

"use strict";


/* ============================================================
   CONFIG
============================================================ */

const PRICE_DATA_URL =
  "data/prices.json";


const PRICE_FINISH_MAP = {
  nonfoil: "normal",
  foil: "foil",
  etched: "etched"
};


/* ============================================================
   STATE
============================================================ */

let priceDatabase = null;
let priceLoading = false;
let priceLoadError = null;


/* ============================================================
   BASIC HELPERS
============================================================ */

function priceMoney(
  value
) {

  const number =
    Number(
      value
    );


  if (
    !Number.isFinite(
      number
    )
  ) {

    return "N/D";
  }


  return (
    "$" +
    number.toFixed(
      2
    )
  );
}


function priceNumberForCsv(
  value
) {

  const number =
    Number(
      value
    );


  if (
    !Number.isFinite(
      number
    )
  ) {

    return "";
  }


  return number.toFixed(
    2
  );
}


function priceCsvCell(
  value
) {

  const text =
    value == null
      ? ""
      : String(
          value
        );


  return /[",\n]/.test(
    text
  )
    ? '"' +
      text.replace(
        /"/g,
        '""'
      ) +
      '"'
    : text;
}


function priceToCsv(
  rows
) {

  return rows
    .map(
      (row) =>
        row
          .map(
            priceCsvCell
          )
          .join(
            ","
          )
    )
    .join(
      "\r\n"
    );
}


function getEntryFinish(
  entry
) {

  if (
    entry?.finish
  ) {

    return entry.finish;
  }


  return entry?.foil
    ? "foil"
    : "nonfoil";
}


function getEntryFinishLabel(
  entry
) {

  const finish =
    getEntryFinish(
      entry
    );


  const labels = {
    nonfoil: "Non-foil",
    foil: "Foil",
    etched: "Etched Foil",
    surgefoil: "Surge Foil",
    galaxyfoil: "Galaxy Foil",
    textured: "Textured Foil",
    review: "Other / Review"
  };


  return (
    labels[
      finish
    ] ||
    finish ||
    "Unknown"
  );
}


/* ============================================================
   PRICE LOOKUP
============================================================ */

function getEntryPrice(
  entry,
  provider
) {

  if (
    !priceDatabase ||
    !entry?.card?.id
  ) {

    return null;
  }


  const finish =
    getEntryFinish(
      entry
    );


  const priceFinish =
    PRICE_FINISH_MAP[
      finish
    ];


  /*
    Special finishes are intentionally NOT mapped to regular foil.
    We prefer N/D over showing a potentially incorrect price.
  */
  if (
    !priceFinish
  ) {

    return null;
  }


  const cardPrices =
    priceDatabase.cards?.[
      entry.card.id
    ];


  const providerPrices =
    cardPrices?.[
      provider
    ];


  const point =
    providerPrices?.[
      priceFinish
    ];


  const value =
    Number(
      point?.price
    );


  if (
    !Number.isFinite(
      value
    )
  ) {

    return null;
  }


  return {
    price:
      value,

    date:
      point?.date ||
      null,

    currency:
      providerPrices?.currency ||
      "USD"
  };
}


function getProviderTotal(
  provider
) {

  let total = 0;
  let pricedLines = 0;


  const totalLines =
    collected.length;


  collected.forEach(
    (entry) => {

      const point =
        getEntryPrice(
          entry,
          provider
        );


      if (
        !point
      ) {

        return;
      }


      const qty =
        Math.max(
          1,
          Number(
            entry.qty
          ) ||
          1
        );


      total +=
        point.price *
        qty;


      pricedLines +=
        1;
    }
  );


  return {
    total,
    pricedLines,
    totalLines,
    complete:
      totalLines > 0 &&
      pricedLines ===
        totalLines
  };
}


function formatProviderTotal(
  provider
) {

  const result =
    getProviderTotal(
      provider
    );


  if (
    result.totalLines === 0
  ) {

    return "$0.00";
  }


  if (
    result.pricedLines === 0
  ) {

    return "N/D";
  }


  const amount =
    priceMoney(
      result.total
    );


  if (
    result.complete
  ) {

    return amount;
  }


  return (
    amount +
    ` · ${result.pricedLines}/${result.totalLines} priced`
  );
}


/* ============================================================
   PRICE DATABASE
============================================================ */

async function loadPriceDatabase(
  force = false
) {

  if (
    priceLoading
  ) {

    return false;
  }


  if (
    priceDatabase &&
    !force
  ) {

    return true;
  }


  priceLoading =
    true;


  priceLoadError =
    null;


  syncPriceControls();
  renderPriceSummary();


  try {

    const url =
      force
        ? `${PRICE_DATA_URL}?refresh=${Date.now()}`
        : PRICE_DATA_URL;


    const response =
      await fetch(
        url,
        {
          cache:
            force
              ? "no-store"
              : "default"
        }
      );


    if (
      !response.ok
    ) {

      throw new Error(
        `HTTP ${response.status}`
      );
    }


    const data =
      await response.json();


    if (
      !data ||
      typeof data !==
        "object" ||
      !data.cards ||
      typeof data.cards !==
        "object"
    ) {

      throw new Error(
        "Invalid price database"
      );
    }


    priceDatabase =
      data;


    priceLoadError =
      null;


    renderPriceUI();


    return true;

  } catch (
    error
  ) {

    console.error(
      "Price database load failed:",
      error
    );


    priceLoadError =
      error;


    renderPriceUI();


    return false;

  } finally {

    priceLoading =
      false;


    syncPriceControls();
    renderPriceSummary();
  }
}


